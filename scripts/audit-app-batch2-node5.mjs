import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
const fail=(m)=>{console.error(`FAIL: ${m}`);process.exitCode=1};
const pass=(m)=>console.log(`PASS: ${m}`);
const req=(s,n,m)=>s.includes(n)?pass(m):fail(m);
const api=read('apps/mobile/src/community/follows.ts');
const screen=read('apps/mobile/app/user/[id].tsx');
const sql=read('supabase/migrations/20260816220000_app_batch2_social_graph.sql');
req(sql,'primary key (follower_user_id, followed_user_id)','duplicate follows prevented by composite primary key');
req(sql,'check (follower_user_id <> followed_user_id)','self-follow prevented server-side');
req(sql,'alter table public.user_follows enable row level security','follow graph RLS enabled');
req(sql,'auth.uid() = follower_user_id','users only mutate their own follow edges');
req(sql,'on delete cascade','deleted accounts remove follow relations');
req(api,'follower_user_id','client API matches follower schema');
req(api,'followed_user_id','client API matches followed schema');
req(api,"target.status !== 'active'",'inactive accounts cannot be newly followed');
req(api,".eq('status', 'active')",'inactive/deactivated users excluded from lists');
req(api,'listFollowers','followers list API exists');
req(api,'listFollowing','following list API exists');
req(screen,'getFollowCounts','user profile renders social counts');
req(screen,"followingTarget ? '取消关注' : '关注'",'follow/unfollow UI exists');
req(screen,'粉丝','followers UI exists');
req(screen,'关注','following UI exists');
if(!process.exitCode) console.log('APP BATCH 2 NODE 5: PASS');
