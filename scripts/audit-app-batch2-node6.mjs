import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
const fail=(m)=>{console.error(`FAIL: ${m}`);process.exitCode=1};
const pass=(m)=>console.log(`PASS: ${m}`);
const req=(s,n,m)=>s.includes(n)?pass(m):fail(m);
const api=read('apps/mobile/src/community/notifications.ts');
const screen=read('apps/mobile/app/notifications.tsx');
const profile=read('apps/mobile/app/(tabs)/profile.tsx');
const base=read('supabase/migrations/20260816220000_app_batch2_social_graph.sql');
const triggers=read('supabase/migrations/20260817023000_app_batch2_notification_triggers.sql');
req(base,'alter table public.user_notifications enable row level security','notification RLS enabled');
req(base,'auth.uid() = user_id','users can only read/update own notifications');
req(api,"'comment_reply' | 'comment_like' | 'follow' | 'system'",'client notification types align with schema');
req(api,'unreadNotificationCount','unread counter API exists');
req(api,'markNotificationRead','single read-state API exists');
req(api,'markAllNotificationsRead','mark-all-read API exists');
req(api,'notificationTarget','notification target routing exists');
req(screen,'消息中心','message center screen exists');
req(screen,'全部已读','mark-all-read UI exists');
req(screen,'notificationTarget','message tap navigation exists');
req(profile,"router.push('/notifications')",'profile links to message center');
req(profile,'unreadNotificationCount','profile surfaces unread count');
req(triggers,'security definer','trusted server-side notification writer exists');
req(triggers,'trg_notify_comment_reply','reply notifications are generated server-side');
req(triggers,'trg_notify_comment_like','like notifications are generated server-side');
req(triggers,'trg_notify_follow','follow notifications are generated server-side');
req(triggers,'revoke all on function public.notify_follow() from public, anon, authenticated','clients cannot invoke trusted writer functions');
if(!process.exitCode) console.log('APP BATCH 2 NODE 6: PASS');
